"""Packs the explosion shader and embeds it in the mod, so installing the mod brings the pack.

From shader/realistic_tnt_shockwave/ (the pack's source) it writes:
  - shader/realistic_tnt_shockwave-<version>.hshader, the pack on its own;
  - realistic_tnt/src/shader_pack_files.rs, the same two files as Rust strings. A .hmod carries only
    Rust and TOML under src/, so the mod holds the pack as text and writes it into the game's
    shaderpacks/ folder on start (src/shader_pack.rs).

Run it after every change to the shader: python tools/embed_shader.py
The mod's tests fail while the embedded copy differs from the source.
"""

import pathlib
import re
import sys
import zipfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "shader" / "realistic_tnt_shockwave"
FILES = ["horizon-shaders.toml", "post/shockwave.wgsl"]
OUT = ROOT / "realistic_tnt" / "src" / "shader_pack_files.rs"


def text(name: str) -> str:
    # The repository stores text with LF endings (.gitattributes); a Windows checkout may hold CRLF.
    return (SOURCE / name).read_bytes().decode("utf-8").replace("\r\n", "\n")


def raw(value: str) -> str:
    hashes = "#"
    while '"' + hashes in value:
        hashes += "#"
    return f'r{hashes}"{value}"{hashes}'


def main() -> int:
    contents = {name: text(name) for name in FILES}
    version = re.search(r'^version = "([^"]+)"', contents["horizon-shaders.toml"], re.M)
    if not version:
        print("horizon-shaders.toml has no version", file=sys.stderr)
        return 1
    version = version.group(1)

    pack = ROOT / "shader" / f"realistic_tnt_shockwave-{version}.hshader"
    with zipfile.ZipFile(pack, "w", zipfile.ZIP_DEFLATED) as archive:
        for name in FILES:
            info = zipfile.ZipInfo(name, date_time=(1980, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o100644 << 16
            archive.writestr(info, contents[name].encode("utf-8"))

    rust = [
        "// Generated by tools/embed_shader.py from shader/realistic_tnt_shockwave/: do not edit.",
        "",
        "/// The pack's version, from its horizon-shaders.toml.",
        f'pub(super) const VERSION: &str = "{version}";',
        "",
        "/// The pack's files: its path inside the pack and its text.",
        "pub(super) const FILES: [(&str, &str); 2] = [",
    ]
    for name in FILES:
        rust.append(f'    ("{name}", {raw(contents[name])}),')
    rust += ["];", ""]
    OUT.write_text("\n".join(rust), encoding="utf-8", newline="\n")
    print(f"wrote {pack.relative_to(ROOT)} and {OUT.relative_to(ROOT)} (pack {version})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
